"""GVLQA-BASE (Yanbin99/GVLQA-BASE) Vision_Only train rows -> verifier-only Candidate records.

Question and answer are the dataset creators' own program-made pair, used as-is (class A): the "<image>" token is
dropped and nothing else about the question changes. Four tasks have a single verifiable answer:
connectivity and cycle (Yes./No. -> two-option MCQ A=Yes, B=No), flow and matching (a nonnegative integer).
Left out because the creators' answer is not one verifiable value: shortest_path, hamilton and topology (a path or
an ordering with several valid answers). Only data/<task>/QA/Vision_Only_train.json is read (the creators' 70% train
file); the *_test.json files and the text/vision+text variants are never opened. Family = graph image, so every
question about one graph lands in one split. Nothing here reads MMMU/MMMU-Pro.
"""
from __future__ import annotations

import json
import re
from collections.abc import Iterator
from pathlib import Path

from ..schema import AnswerType
from .hf_common import Candidate, SourceSpec

SOURCE_GVLQA = "hf-gvlqa"
YES_NO_TASKS = ("connectivity", "cycle")
INT_TASKS = ("flow", "matching")
_IMAGE_PATH = re.compile(r"data/(\w+)/graph_visual/(easy|medium|hard)/(graph\d+)\.png")

SPECS: dict[str, SourceSpec] = {
    SOURCE_GVLQA: SourceSpec(
        SOURCE_GVLQA, "Yanbin99/GVLQA-BASE", "7aeff19faa34ddb19f79b8a5a80d31c1fe9db18b", "MIT", "PROGRAM",
        "GVLQA-BASE question/answer pairs generated by the dataset creators' graph programs (Wei et al. 2024)",
        "graph",
    ),
}


def _answer(task: str, value: object) -> tuple[tuple[str, ...], AnswerType, str] | None:
    """(choices, answer_type, gold) for the creators' answer string, or None when it is not a single value."""
    if not isinstance(value, str):
        return None
    text = value.strip().removesuffix(".").strip()
    if task in YES_NO_TASKS:
        return (("Yes", "No"), "mcq", "A" if text == "Yes" else "B") if text in ("Yes", "No") else None
    return ((), "int", str(int(text))) if re.fullmatch(r"\d{1,6}", text) else None


def iter_gvlqa(repo_dir: Path) -> Iterator[Candidate]:
    root = Path(repo_dir)
    for task in (*YES_NO_TASKS, *INT_TASKS):
        for row in json.loads((root / "data" / task / "QA" / "Vision_Only_train.json").read_text(encoding="utf-8")):
            image = _IMAGE_PATH.fullmatch(row["image"]) if isinstance(row.get("image"), str) else None
            human, gpt = row["conversations"]
            question = human["value"].removeprefix("<image>\n").strip()
            parsed = _answer(task, gpt["value"])
            if image is None or image.group(1) != task or not question or parsed is None:
                continue
            raw = root / row["image"]
            if not raw.is_file():
                continue
            choices, answer_type, gold = parsed
            yield Candidate(
                source=SOURCE_GVLQA, native_id=row["id"], subject="Computer_Science", question=question,
                choices=choices, answer_type=answer_type, gold=gold, images=(raw.read_bytes(),),
                family_key=f"{task}-{image.group(2)}-{image.group(3)}",
            )


ITERATORS = {SOURCE_GVLQA: iter_gvlqa}
