"""Synthetic CPU gate boundaries; not model evaluation or a real image review."""
from __future__ import annotations

import builtins
import copy
import sys
import unittest
from pathlib import Path
from unittest.mock import patch

from fine_tuning.notebook_rl import local_ladder_gate as gate
from fine_tuning.notebook_rl import local_ladder_generation, local_ladder_recovery
from fine_tuning.notebook_rl.dataset import _bytes, _write
from fine_tuning.tests import test_notebook_rl_local_ladder as fixtures


class GateTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        fixtures.LocalLadderTests.setUpClass()

    def setUp(self):
        self.fixture = fixtures.LocalLadderTests()
        self.fixture.setUp()
        self.addCleanup(self.fixture.doCleanups)
        self.fixture.prepare()
        self.root, self.prep = self.fixture.out, self.fixture.path
        self.protocol = local_ladder_generation.protocol({"fixture": True}, "a" * 64)
        actors = gate.ladder.load_ladder_actors(self.root)
        self.review = self.fixture.base / "review.json"
        self.review_data = {"status": "AI_REVIEWED_NOT_HUMAN_VERIFIED", "human_verified": False,
            "gold_exposed_to_reviewer": True, "model_payload_contains_review": False,
            "scope": "all-images-values-units-polarity-connections-query-target",
            "preparation": gate.ladder._descriptor(self.root / "preparation.json"),
            "rows": [{"problem_id": a.problem_id, "image_sha256": list(a.image_sha256),
                      "verdict": "NO_MISMATCH_OBSERVED"} for a in actors]}
        _write(self.review, _bytes(self.review_data))
        self.output = self.fixture.base / "gate.json"

    def build(self):
        # Native generated bytes are cached for speed; both exact solvers still run.
        with patch.object(gate.circuit, "generate", side_effect=lambda i, *args: self.fixture.ladders[i]):
            return gate.build_gate(self.root, self.prep, self.review, self.output, self.protocol)

    def test_trusted_reconstruction_and_public_validation_without_private_reads(self):
        originals = {p: p.read_bytes() for p in self.fixture.base.rglob("*") if p.is_file()}
        result = self.build()
        self.assertEqual(result["status"], gate.STATUS)
        self.assertTrue(all(result["checks"].values()))
        self.assertFalse(result["training_allowed"])
        self.assertFalse(result["gpu_execution_authorized"])
        self.assertFalse(result["human_verified"])
        self.assertEqual(len(result["problem_ids"]), 10)
        raw_open = builtins.open

        def public_only(file, *args, **kwargs):
            if isinstance(file, (str, Path)) and Path(file).name in ("verifier_private.jsonl", "lineage.jsonl"):
                raise AssertionError("private reference read by public validator")
            return raw_open(file, *args, **kwargs)

        with patch.object(builtins, "open", side_effect=public_only), \
                patch.object(gate, "read_verifier", side_effect=AssertionError("private verifier")), \
                patch.object(gate, "read_lineage", side_effect=AssertionError("private lineage")), \
                patch.object(gate.ladder, "_training", side_effect=AssertionError("trusted audit in actor")):
            self.assertEqual(gate.validate_gate(self.root, self.prep, self.output, self.protocol), result)
        self.assertTrue(all(p.read_bytes() == raw for p, raw in originals.items()))
        with self.assertRaises(ValueError):
            self.build()

    def test_missing_or_partial_review_and_changed_image_binding_block_output(self):
        for changes in ({"rows": self.review_data["rows"][:-1]}, {"human_verified": True},
                        {"model_payload_contains_review": True}, {"status": "PENDING"}):
            self.review.write_bytes(_bytes(self.review_data | changes))
            with self.assertRaisesRegex(ValueError, "image review"):
                self.build()
            self.assertFalse(self.output.exists())
        changed = copy.deepcopy(self.review_data)
        changed["rows"][0]["image_sha256"] = ["0" * 64]
        self.review.write_bytes(_bytes(changed))
        with self.assertRaisesRegex(ValueError, "image review"):
            self.build()

    def test_native_reference_or_generated_payload_drift_is_not_authorized(self):
        from dataclasses import replace
        first = self.fixture.ladders[gate.ladder.INDICES[0]]
        bad = replace(first, actor=replace(first.actor, question="Changed native question"))
        with patch.object(gate.circuit, "generate", return_value=bad):
            with self.assertRaises(ValueError):
                gate.build_gate(self.root, self.prep, self.review, self.output, self.protocol)
        self.assertFalse(self.output.exists())

    def test_source_protocol_preparation_and_pending_receipt_drift_are_rejected(self):
        result = self.build()
        for changes in ({"status": "CPU_COHORT_PREPARED_PENDING_GATES"}, {"checks": {}},
                        {"training_allowed": True}, {"gpu_execution_authorized": True},
                        {"problem_ids": result["problem_ids"][::-1]}, {"source_sha256": {}},
                        {"protocol_sha256": "0" * 64}, {"public_inputs_sha256": {}}):
            self.output.write_bytes(_bytes(result | changes))
            with self.assertRaises(ValueError):
                gate.validate_gate(self.root, self.prep, self.output, self.protocol)
        self.output.write_bytes(_bytes(result))
        with self.assertRaises(ValueError):
            gate.validate_gate(self.root, self.prep, self.output, self.protocol | {"n": 2})
        self.review.write_bytes(_bytes(self.review_data | {"extra": "changed review"}))
        with self.assertRaisesRegex(ValueError, "review changed"):
            gate.validate_gate(self.root, self.prep, self.output, self.protocol)

    def test_only_exact_canonical_first_attempt_or_recovery_protocols_are_authorized(self):
        for module in (local_ladder_generation, local_ladder_recovery):
            canonical = module.protocol({"fixture": True}, "a" * 64)
            gate._validate_protocol(canonical)
            for changes in ({"max_attempts": 2}, {"max_attempts": float(canonical["max_attempts"])},
                            {"n": 2}, {"n": True}, {"max_new_tokens": 32},
                            {"context_limit": 8192}, {"protocol_id": "unknown"}, {"extra": "extension"},
                            {"prompt_templates_sha256": "invalid"}, {"local_protocol_sha256": "A" * 64}):
                with self.subTest(module=module.VERSION, changes=changes), self.assertRaisesRegex(ValueError, "canonical"):
                    gate._validate_protocol(canonical | changes)
            if module is local_ladder_recovery:
                with self.assertRaisesRegex(ValueError, "canonical"):
                    gate._validate_protocol(canonical | {"notebook": canonical["notebook"] | {"max_new_tokens": 1024}})
        self.protocol = local_ladder_recovery.protocol({"fixture": True}, "a" * 64)
        result = self.build()
        self.assertEqual(gate.validate_gate(self.root, self.prep, self.output, self.protocol), result)
        sources = result["source_sha256"]
        self.assertIn(str(Path(local_ladder_recovery.__file__).resolve()), sources)
        self.assertIn(str(Path(gate.__file__).with_name("local_ladder_score.py").resolve()), sources)
        with self.assertRaisesRegex(ValueError, "stale"):
            gate.validate_gate(self.root, self.prep, self.output,
                               local_ladder_generation.protocol({"fixture": True}, "a" * 64))

    def test_24k_gate_requires_canonical_context_and_cannot_reuse_16k_receipt(self):
        for module in (local_ladder_generation, local_ladder_recovery):
            canonical = module.protocol({"fixture": True}, "a" * 64, context_limit=24576)
            gate._validate_protocol(canonical)
            for context in (True, 24576., 8192, 32768, "24576", None):
                with self.subTest(module=module.VERSION, context=context), self.assertRaises(ValueError):
                    gate._validate_protocol(canonical | {"context_limit": context})
        self.protocol = local_ladder_recovery.protocol({"fixture": True}, "a" * 64, context_limit=24576)
        result = self.build()
        self.assertEqual(gate.validate_gate(self.root, self.prep, self.output, self.protocol), result)
        with self.assertRaisesRegex(ValueError, "stale"):
            gate.validate_gate(self.root, self.prep, self.output,
                local_ladder_recovery.protocol({"fixture": True}, "a" * 64))

    def test_cold_import_and_canonical_validation_do_not_load_models_or_initialize_cuda(self):
        import os
        import subprocess
        env = dict(os.environ, CUDA_VISIBLE_DEVICES="", PYTHONDONTWRITEBYTECODE="1")
        code = "import sys; from fine_tuning.notebook_rl import local_ladder_gate; "
        code += "assert not {'torch','transformers','peft','bitsandbytes'} & sys.modules.keys(); "
        code += "from fine_tuning.notebook_rl import local_ladder_recovery; "
        code += "local_ladder_gate._validate_protocol(local_ladder_recovery.protocol({}, 'a'*64)); "
        code += "assert not {'transformers','peft','bitsandbytes'} & sys.modules.keys(); "
        code += "assert not sys.modules['torch'].cuda.is_initialized()"
        checked = subprocess.run([sys.executable, "-B", "-c", code], env=env, capture_output=True, timeout=30)
        self.assertEqual(checked.returncode, 0, checked.stderr.decode())


if __name__ == "__main__":
    unittest.main()
