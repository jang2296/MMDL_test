"""Native CPU-only ladder preparation and actor/gold separation boundaries."""
from __future__ import annotations

import json
import tempfile
import unittest
from dataclasses import replace
from pathlib import Path
from unittest.mock import patch

from fine_tuning.notebook_rl import local_ladder as ladder
from fine_tuning.notebook_rl.dataset import _bytes, _sha, _write
from fine_tuning.notebook_rl.generators import circuit, graph, graph_pair
from fine_tuning.notebook_rl.schema import to_json
from fine_tuning.notebook_rl.vault import read_lineage, read_verifier, write_split


class LocalLadderTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.training_rows = [graph.generate(i, 3407, "train", "obs") for i in (1, 2, 3, 5, 6)]
        cls.training_rows += [graph_pair.generate(i, 3407, "train", "obs") for i in range(5)]
        cls.all_rows = cls.training_rows + [graph.generate(i, 3407, "train", "obs") for i in (0, 4, 7)]
        cls.all_rows += [graph_pair.generate(i, 3407, "train", "obs") for i in (5, 6, 7)]
        cls.ladders = {i: circuit.generate(i, ladder.SEED, "sealed", "obs") for i in ladder.INDICES}

    def setUp(self):
        temporary = tempfile.TemporaryDirectory()
        self.addCleanup(temporary.cleanup)
        self.base = Path(temporary.name)
        self.root, self.prepared = self.base / "build", self.base / "prepared"
        rows = self.training_rows
        write_split(self.root / "train", [r.actor for r in self.all_rows],
                    [r.verifier for r in self.all_rows], [r.lineage for r in self.all_rows])
        for row in rows:
            for rel, raw in zip(row.actor.image_paths, row.image_bytes, strict=True):
                _write(self.root / "images" / rel, raw)
        self.prepared.mkdir()
        self.selection = {"status": "LOCAL_FIXED_TEN_NOT_TRAINING_APPROVAL",
            "local_protocol_sha256": "a" * 64, "problem_ids": [r.actor.problem_id for r in rows],
            "structures": {r.actor.problem_id: r.lineage.structure_hash for r in rows},
            "image_counts": {r.actor.problem_id: len(r.actor.image_paths) for r in rows}}
        self.prep = {"format": "notebook-rl-local-data-v1", "status": "LOCAL_DATA_REVALIDATED",
            "training_allowed": False, "local_protocol_sha256": "a" * 64,
            "build_root": str(self.root), "image_root": str(self.root / "images")}
        previous = self.prepared / "previous_selection.json"
        _write(previous, _bytes(self.selection))
        self.prep["previous_selection"] = ladder._descriptor(previous)
        self.selection["previous_selection"] = self.prep["previous_selection"]
        _write(self.root / "manifest.yaml", _bytes({"format": "notebook-rl-candidate-build-v1",
            "training_allowed": False, "counts": {"train": 16}, "split_manifests": {
                "train": ladder._descriptor(self.root / "train/manifest.yaml")["file_sha256"]}}))
        self.bind("selection", self.selection)
        self.bind("actors", [json.loads(to_json(r.actor)) for r in rows])
        self.bind("data_request", {"build_root": str(self.root)})
        self.validated = {"status": "VALIDATED_FOR_MEASUREMENT", "training_allowed": False,
            "measurement_allowed": True, "blockers": [],
            "input_binding": {"build_manifest_sha256": ladder._descriptor(self.root / "manifest.yaml")["file_sha256"]},
            "selected_ids": [r.actor.problem_id for r in self.all_rows],
            "actors": [json.loads(to_json(r.actor)) for r in self.all_rows],
            "structures": {r.actor.problem_id: r.lineage.structure_hash for r in self.all_rows}}
        self.bind("validated_data", self.validated)
        self.path = self.prepared / "preparation.json"
        _write(self.path, _bytes(self.prep))
        self.out = self.base / "ladder"

    def bind(self, key, value):
        path = self.prepared / f"{key}.json"
        if path.exists():
            path.write_bytes(_bytes(value))
        else:
            _write(path, _bytes(value))
        self.prep[key] = ladder._descriptor(path)

    def prepare(self):
        # Reuse native generated bytes for boundary tests; self_check remains real.
        with patch.object(circuit, "generate", side_effect=lambda i, *args: self.ladders[i]):
            return ladder.prepare_ladder_data(self.path, self.out)

    def test_native_deterministic_cohort_and_public_loader_never_open_gold(self):
        before = {p: p.read_bytes() for p in self.base.rglob("*") if p.is_file()}
        result = ladder.prepare_ladder_data(self.path, self.out)
        self.assertEqual(result["count"], 10)
        self.assertEqual(result["training_node_counts"], [4, 7, 8])
        self.assertEqual(result["ladder_node_counts"], [5, 6])
        self.assertEqual(result["topology_family_count"], 3)
        self.assertTrue(all(result["separation"].values()))
        self.assertFalse(result["training_allowed"])
        self.assertFalse(result["evaluation_allowed"])
        self.assertFalse(result["new_exclusion_scan_performed"])
        self.assertEqual(result["source_before_sha256"], result["source_after_sha256"])
        self.assertTrue({"circuit_bridge.py", "nvw.py", "ablation.py", "graph_bridge.py", "guards.py"}
                        <= {Path(p).name for p in result["source_before_sha256"]})
        opened = []
        original = ladder.vault._read

        def public_read(path):
            opened.append(Path(path).name)
            self.assertNotIn(Path(path).name, ("verifier_private.jsonl", "lineage.jsonl"))
            return original(path)

        with patch.object(ladder.vault, "_read", side_effect=public_read):
            actors = ladder.load_ladder_actors(self.out)
        self.assertIn("actor_inputs.jsonl", opened)
        self.assertEqual([a.problem_id for a in actors], result["problem_ids"])
        self.assertTrue(all(a.answer_format == "unit_number" and a.mode == "obs" and not a.choices for a in actors))
        self.assertEqual({row.source_revision for row in read_lineage(self.out / "records").values()},
                         {result["source_revision"]})
        for path, raw in before.items():
            self.assertEqual(path.read_bytes(), raw)
        second = ladder.prepare_ladder_data(self.path, self.base / "second")
        self.assertEqual(result["problem_ids"], second["problem_ids"])
        self.assertEqual((self.out / "records/actor_inputs.jsonl").read_bytes(),
                         (self.base / "second/records/actor_inputs.jsonl").read_bytes())
        self.assertEqual(read_verifier(self.out / "records"), read_verifier(self.base / "second/records"))

    def test_descriptor_actor_selection_and_vault_tampering_fail_before_output(self):
        for name in ("selection.json", "actors.json", "data_request.json", "validated_data.json"):
            path = self.prepared / name
            raw = path.read_bytes()
            path.write_bytes(raw + b" ")
            with self.subTest(name=name), self.assertRaisesRegex(ValueError, "bound input changed"):
                self.prepare()
            self.assertFalse(self.out.exists())
            path.write_bytes(raw)
        for name in ("actor_inputs.jsonl", "verifier_private.jsonl", "lineage.jsonl"):
            path = self.root / "train" / name
            raw = path.read_bytes()
            path.write_bytes(raw + b" ")
            with self.subTest(name=name), self.assertRaises(ValueError):
                self.prepare()
            self.assertFalse(self.out.exists())
            path.write_bytes(raw)

    def test_rehashed_wrong_selection_or_actor_and_retargeted_root_are_rejected(self):
        changes = (("selection", self.selection | {"problem_ids": self.selection["problem_ids"][:9]}),
                   ("actors", [json.loads(to_json(r.actor)) for r in reversed(self.training_rows)]),
                   ("data_request", {"build_root": str(self.base)}))
        for key, value in changes:
            old_descriptor = self.prep[key]
            old_raw = Path(old_descriptor["path"]).read_bytes()
            self.bind(key, value)
            self.path.write_bytes(_bytes(self.prep))
            with self.subTest(key=key), self.assertRaises(ValueError):
                self.prepare()
            self.assertFalse(self.out.exists())
            Path(old_descriptor["path"]).write_bytes(old_raw)
            self.prep[key] = old_descriptor
            self.path.write_bytes(_bytes(self.prep))

    def test_rehashed_private_vault_and_build_cannot_replace_validated_inputs(self):
        verifier_path = self.root / "train/verifier_private.jsonl"
        rows = [json.loads(line) for line in verifier_path.read_bytes().splitlines()]
        rows[0]["gold"] = "999999"
        verifier_path.write_bytes(b"".join(_bytes(row) + b"\n" for row in rows))
        train_manifest_path = self.root / "train/manifest.yaml"
        train_manifest = json.loads(train_manifest_path.read_bytes())
        train_manifest["files"]["verifier_private.jsonl"]["sha256"] = _sha(verifier_path.read_bytes())
        train_manifest_path.write_bytes(_bytes(train_manifest))
        with self.assertRaisesRegex(ValueError, "bound input changed"):
            self.prepare()
        build_path = self.root / "manifest.yaml"
        build = json.loads(build_path.read_bytes())
        build["split_manifests"]["train"] = _sha(train_manifest_path.read_bytes())
        build_path.write_bytes(_bytes(build))
        with self.assertRaisesRegex(ValueError, "bound input changed"):
            self.prepare()
        self.assertFalse(self.out.exists())

    def test_validated_permission_actors_and_structures_are_checked(self):
        for change in ({"measurement_allowed": False}, {"blockers": ["BLOCKED"]},
                       {"selected_ids": self.validated["selected_ids"][:10]},
                       {"actors": self.validated["actors"][:10]}, {"structures": {}}):
            self.bind("validated_data", self.validated | change)
            self.path.write_bytes(_bytes(self.prep))
            with self.subTest(change=list(change)), self.assertRaises(ValueError):
                self.prepare()
            self.assertFalse(self.out.exists())

    def test_reselecting_other_validated_training_items_is_rejected(self):
        rows = self.training_rows.copy()
        rows[0] = self.all_rows[10]
        self.bind("selection", self.selection | {
            "problem_ids": [r.actor.problem_id for r in rows],
            "structures": {r.actor.problem_id: r.lineage.structure_hash for r in rows},
            "image_counts": {r.actor.problem_id: len(r.actor.image_paths) for r in rows}})
        self.bind("actors", [json.loads(to_json(r.actor)) for r in rows])
        self.path.write_bytes(_bytes(self.prep))
        with self.assertRaisesRegex(ValueError, "selection binding"):
            self.prepare()
        self.assertFalse(self.out.exists())

    def test_post_write_input_and_source_changes_prevent_completion_marker(self):
        original = ladder.cli.write_pool

        def mutate_after_write(*args, **kwargs):
            result = original(*args, **kwargs)
            self.path.write_bytes(self.path.read_bytes() + b" ")
            return result

        with patch.object(ladder.cli, "write_pool", side_effect=mutate_after_write):
            with self.assertRaisesRegex(ValueError, "changed during"):
                self.prepare()
        self.assertTrue((self.out / "pool.json").exists())
        self.assertFalse((self.out / "preparation.json").exists())
        self.out = self.base / "source_changed"
        with patch.object(ladder, "_sources", side_effect=[{"first": "a"}, {"first": "a"}, {"first": "b"}]):
            with self.assertRaisesRegex(ValueError, "changed during"):
                self.prepare()
        self.assertFalse((self.out / "preparation.json").exists())

    def test_node_count_overlap_and_unsupported_world_are_rejected(self):
        with patch.object(ladder, "_graph_nodes", return_value=5):
            with self.assertRaisesRegex(ValueError, "overlap"):
                self.prepare()
        self.assertFalse(self.out.exists())
        for world in ({"kind": "unknown"}, {"kind": "bfs", "nodes": ["A"]}, None):
            with self.subTest(world=world), self.assertRaisesRegex(ValueError, "unsupported"):
                ladder._graph_nodes(world)

    def test_path_aliases_inside_input_and_existing_outputs_are_rejected(self):
        self.out.mkdir()
        sentinel = self.out / "keep"
        sentinel.write_text("keep")
        with self.assertRaises(FileExistsError):
            self.prepare()
        self.assertEqual(sentinel.read_text(), "keep")
        for out in (self.prepared / "new", self.root / "new", self.base / ".." / "alias"):
            with self.subTest(out=out), self.assertRaises(ValueError):
                ladder.prepare_ladder_data(self.path, out)
        alias = self.base / "alias"
        alias.symlink_to(self.prepared, target_is_directory=True)
        with self.assertRaisesRegex(ValueError, "symlink"):
            ladder.prepare_ladder_data(alias / "preparation.json", self.base / "new")
        with self.assertRaisesRegex(ValueError, "aliases"):
            ladder.prepare_ladder_data(self.path, alias / "new")

    def test_self_check_generation_determinism_and_source_changes_abort(self):
        row = self.ladders[ladder.INDICES[0]]
        broken = replace(row, verifier=replace(row.verifier, gold="999 A"))
        with patch.object(circuit, "generate", return_value=broken):
            with self.assertRaisesRegex(ValueError, "self-check"):
                ladder.prepare_ladder_data(self.path, self.out)
        with patch.object(circuit, "generate", side_effect=[row, replace(row,
                lineage=replace(row.lineage, source_revision="different"))]):
            with self.assertRaisesRegex(ValueError, "nondeterministic"):
                ladder.prepare_ladder_data(self.path, self.out)
        with patch.object(ladder, "_sources", side_effect=[{"first": "a"}, {"first": "b"}]):
            with self.assertRaisesRegex(ValueError, "changed during"):
                self.prepare()
        self.assertFalse(self.out.exists())


if __name__ == "__main__":
    unittest.main()
